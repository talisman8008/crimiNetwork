export function eventsForCase(caseId: string): TimelineEvent[] {
  return timelineEvents
    .filter((e) => e.caseId === caseId)
    .sort((a, b) => `${a.date} ${a.time}`.localeCompare(`${b.date} ${b.time}`));
}

export function eventsForEntity(entityId: string): TimelineEvent[] {
  return timelineEvents
    .filter((e) => e.entityIds.includes(entityId))
    .sort((a, b) => `${a.date} ${a.time}`.localeCompare(`${b.date} ${b.time}`));
}

export function eventsWithLocation(): TimelineEvent[] {
  return timelineEvents.filter((e) => e.lat != null && e.lng != null);
}

/** All distinct day-stamps present in the event log, ascending. */
export function eventDates(events: TimelineEvent[]): string[] {
  return [...new Set(events.map((e) => e.date))].sort();
}

export function formatDuration(sec: number): string {
  const m = Math.floor(sec / 60);
  const s = sec % 60;
  return m > 0 ? `${m}m ${s}s` : `${s}s`;
}

